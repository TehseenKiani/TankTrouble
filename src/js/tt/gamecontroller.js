    setGameState(gameState) {
        // Iterate over playerstates and call setPlayerState.
        const playerStates = gameState.getPlayerStates();
        for (const playerState of playerStates) {
            this.setPlayerState(playerState);
        }

        // Iterate over active players and check if they are still in the gamestate.
        const activePlayers = this.model.getActivePlayers();
        for (const player in activePlayers) {
            const playerId = activePlayers[player].getId();
            const playerFound = playerStates.some(playerState => playerState.getPlayerId() === playerId);
            if (!playerFound) {
                this.removePlayer(playerId);
            }
        }

        this.setMode(gameState.getMode());
        this.setMaxActivePlayerCount(gameState.getMaxActivePlayerCount());
        this.setTheme(gameState.getTheme());
        this.setRanked(gameState.getRanked());
        this.setSymmetric(gameState.getSymmetric());
        this.setStorm(gameState.getStorm());
        this.setPremium(gameState.getPremium());

        // Iterate over scoreStates and call setScoreState.
        const scoreStates = gameState.getScoreStates();
        for (const scoreState of scoreStates) {
            this.setScoreState(scoreState);
        }

        // Iterate over scores and check if they are still in the gamestate.
        const scores = this.model.getScores();
        for (const score in scores) {
            const scoreId = scores[score].getId();
            const scoreFound = scoreStates.some(scoreState => scoreState.getId() === scoreId);
            if (!scoreFound) {
                this.removeScore(scoreId);
            }
        }

        // Iterate over emblemStates and call setEmblemState.
        const emblemStates = gameState.getEmblemStates();
        for (const emblemState of emblemStates) {
            this.setEmblemState(emblemState);
        }

        // Iterate over emblems and check if they are still in the gamestate.
        const emblems = this.model.getEmblems();
        for (const emblem in emblems) {
            const emblemId = emblems[emblem].getId();
            const emblemFound = emblemStates.some(emblemState => emblemState.getId() === emblemId);
            if (!emblemFound) {
                this.removeEmblem(emblemId);
            }
        }

        this.model.emitGameState(gameState);
    }

