    static withIds(id, localPlayerIds) {
        const instance = new this();
        instance.id = id;
        instance.localPlayerIds = localPlayerIds;
        instance._initialise(null, null, null);
        return instance;
    }

    _initialise(mode, maxActivePlayerCount, theme) {
        this.log = new Log("GameController");
        this.model = new GameModel(this.id, mode, maxActivePlayerCount, theme);
        // We only want to handle events generated by the model when we are not
        // receiving instructions from the outside (ie. only if we are in local mode,
        // or in server mode)
        if (Constants.getMode() === Constants.MODE_SERVER || Constants.getMode() === Constants.MODE_CLIENT_LOCAL) {
            this.model.addEventListener(this._gameModelEventHandler, this, this.id);
        }

        // Set initial state.
        this.model.setState(GameModel._STATES.BETWEEN_ROUNDS);

        // Create round controller.
        this._createRoundController();
    }

    /**
     * Move GameController to the next frame
     */
    update() {
        const time = new Date();
        let deltaTime = (time - this.lastUpdate) / 1000.0;
        this.lastUpdate = time;

        // Modify deltaTime if too large.
        deltaTime = Math.min(deltaTime, Constants.MAX_DELTA_TIME);

        if (this.roundController) {
            this.roundController.update(deltaTime);
        }

        // Only do game logic if local client or server.
        if (Constants.getMode() === Constants.MODE_CLIENT_LOCAL || Constants.getMode() === Constants.MODE_SERVER) {
            switch (this.model.getState()) {
                case GameModel._STATES.BETWEEN_ROUNDS:
                {
                    // Wait a few seconds before creating celebration..
                    if (Constants.GAME_MODE_INFO[this.model.getMode()].HAS_CELEBRATION) {
                        if (!this.celebrationStarted) {
                            this.celebrationDuration += deltaTime;
                            if (this.celebrationDuration > Constants.BETWEEN_ROUNDS_DURATION) {
                                this.celebrationDuration = 0.0;
                                this._initialiseCelebration();
                            }
                        }
                    }

                    // Wait a few seconds before creating next round..
                    let durationToWait = Constants.BETWEEN_ROUNDS_DURATION;
                    if (Constants.GAME_MODE_INFO[this.model.getMode()].HAS_CELEBRATION) {
                        durationToWait += Constants.CELEBRATION_DURATION;
                    }
                    this.betweenRoundsDuration += deltaTime;
                    if (this.betweenRoundsDuration > durationToWait) {
                        if (!this.celebrationEnded) {
                            // This ensures that players wanting to leave, can do so.
                            this._endCelebration();
                        }

                        if (this.model.getTotalPlayerCount() >= Constants.GAME_MODE_INFO[this.model.getMode()].MIN_PLAYERS) {
                            this.betweenRoundsDuration = 0.0;
                            this.celebrationStarted = false;
                            this.celebrationEnded = false;
                            this.log.debug("Enough players available in game to start playing");
                            // This call also sets the state to COUNTING_DOWN
                            this._initialiseRound();
                        } else {
                            // Intentionally do nothing here
                        }
                    }
                    break;
                }
                case GameModel._STATES.COUNTING_DOWN:
                {
                    // Manage the countdown
                    this.countDownDuration += deltaTime;
                    if (this.countDownDuration >= Constants.COUNTDOWN_DURATION) {
                        this.countDownDuration = 0.0;
                        if (this.countDownValue > 0) {
                            this.countDown(this.countDownValue);
                            --this.countDownValue;
                        } else {
                            this.countDownValue = Constants.COUNTDOWN_START_VALUE;
                            this.startRound();
                        }
                    }
                    break;
                }
                case GameModel._STATES.IN_ROUND:
                {
                    break;
                }
                default:
                {
                    this.log.error(`Unknown state ${this.model.getState()} in GameModel._gameModelStateHandler`);
                }
            }

            if (Constants.getMode() === Constants.MODE_SERVER) {
                // If there are no players left, game has ended
                if (this.model.getTotalPlayerCount() === 0) {
                    this.model.setState(GameModel._STATES.ENDED);
                }
            } else if (Constants.getMode() === Constants.MODE_CLIENT_LOCAL) {
                // If there is only one player left, game has ended
                if (this.model.getTotalPlayerCount() <= 1) {
                    this.model.setState(GameModel._STATES.ENDED);
                }
            }

            // Update model.
            this.model.update();
        }
    }

