    _endCelebration() {
        this.celebrationEnded = true;

        this.roundController.endCelebration();
    }

    _initialiseRound() {
        let nextQueuedPlayerId = this.model.getNextQueuedPlayerId();
        while (this.model.getActivePlayerCount() < this.model.getMaxActivePlayerCount() && (nextQueuedPlayerId !== null)) {
            // While there is room in the game, and more queued players,
            // move players into the active players list
            this.log.debug(`Activating player ${nextQueuedPlayerId}`);
            this.model.activatePlayer(nextQueuedPlayerId);
            nextQueuedPlayerId = this.model.getNextQueuedPlayerId();
        }

        // Update game mode with ranked status.
        this.gameMode.setRanked(this.ranked);

        // Update game mode with symmetric status.
        this.gameMode.setSymmetric(this.symmetric);

        // Update game mode with storm status.
        this.gameMode.setStorm(this.storm);

        // Update game mode with crate types.
        this.gameMode.setCrateTypes(this.crateTypes);

        // Create new round controller.
        this._createRoundController();

        // Call create to notify listeners of round's creation.
        this.roundController.createRound(this.ranked);

        // Create maze.
        const maze = this.gameMode.getMaze(this.getActivePlayerIds(), this.model.getTheme() !== Constants.MAZE_THEMES.RANDOM ? this.model.getTheme() : MazeThemeManager.getRandomActiveTheme());

        // Set maze on the round.
        this.setMaze(maze);

        // Stuff appropriate players into the round controller
        // in the form of tanks
        const tankPositions = maze.getTankPositions();
        for (const tankPosition of tankPositions) {
            this.roundController.spawnTank(tankPosition.playerId, tankPosition, false);
        }

        // Tell the game mode to reset for a new round.
        this.gameMode.initialiseRound();

        // Change state to counting down.
        this.model.setState(GameModel._STATES.COUNTING_DOWN);
    }

    countDown(value) {
        if (this.model.getState() === GameModel._STATES.BETWEEN_ROUNDS) {
            this.model.countDown(value);

            // Change state to counting down.
            this.model.setState(GameModel._STATES.COUNTING_DOWN);
        } else if (this.model.getState() === GameModel._STATES.COUNTING_DOWN) {
            this.model.countDown(value);
        } else {
            this.log.error(`Attempt to count down in game which is currently in state ${this.model.getState()}`);
        }
    }

    endRound(victoryAward) {
        if (this.model.getState() === GameModel._STATES.IN_ROUND) {
            this.roundController.endRound(victoryAward);

            // Change state to between rounds.
            this.model.setState(GameModel._STATES.BETWEEN_ROUNDS);
        } else if (this.model.getState() === GameModel._STATES.BETWEEN_ROUNDS && Constants.getMode() === Constants.MODE_CLIENT_ONLINE) {
            this.roundController.endRound(victoryAward);

            this.log.debug("In state BETWEEN_ROUNDS when round ended. Player was spectating and joined after last countdown message.");
        } else {
            this.log.error(`Attempt to end round in game which is currently in state ${this.model.getState()}`);
        }
    }

