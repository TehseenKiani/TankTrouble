    setTankState(tankState) {
        if (this.model.getState() !== GameModel._STATES.IN_ROUND) {
            this.log.warn(`Player with id ${tankState.getPlayerId()} attempted to set tank state with game in state ${this.model.getState()}`);
            return false;
        }
        if (!this.model.isPlayerActive(tankState.getPlayerId())) {
            this.log.warn(`Player with id ${tankState.getPlayerId()} attempted to set tank state while not active in game`);
            return false;
        }

        if (this.roundController) {
            return this.roundController.setTankState(tankState, false);
        }

        return false;
    }

    addPlayer(playerId) {
        const success = this.model.addPlayer(playerId, Constants.TEAMS.NO_TEAM);
        if (success) {
            // Only set up scores if local client or server.
            if (Constants.getMode() === Constants.MODE_CLIENT_LOCAL || Constants.getMode() === Constants.MODE_SERVER) {
                const scoreStates = this.gameMode.getScoreStates(playerId);
                for (const scoreState of scoreStates) {
                    this.setScoreState(scoreState);
                }
            }

            this.playerAdded = true;
        }

        return success;
    }

    removePlayer(playerId) {
        this.log.debug(`Removing player ${playerId}`);
        if (this.model.isPlayerActive(playerId)) {
            this.log.debug(`Player ${playerId} is marked as active, so removing from round`);
            if (this.roundController && this.roundController.getTank(playerId) !== undefined) {
                this.roundController.removeTank(playerId);
            }
        } else {
            this.log.debug(`Player ${playerId} not marked as active, so not removing from round`);
        }
        return this.model.removePlayer(playerId);
    }

    canRemovePlayers(playerIds) {
        // If game is not in a round, it's always okay to remove players.
        if (this.model.getState() === GameModel._STATES.BETWEEN_ROUNDS || this.model.getState() === GameModel._STATES.ENDED) {
            return true;
        }

        // Otherwise, we need to ask the game mode for each active player.
        for (const playerId of playerIds) {
            if (this.model.isPlayerActive(playerId)) {
                if (!this.gameMode.canRemovePlayer(playerId)) {
                    return false;
                }
            }
        }

        return true;
    }

