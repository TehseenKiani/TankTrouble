    _createRoundController() {
        this.log.debug(`Game id: ${this.id}. Queued player count: ${this.getQueuedPlayerCount()}`);
        this.log.debug(`Game id: ${this.id}. Active player count: ${this.getActivePlayerCount()}`);
        if (this.model.getState() === GameModel._STATES.BETWEEN_ROUNDS) {
            // Ensure that old objects get released.
            this.roundController = null;

            // Create a new round controller
            this.roundController = new RoundController(this.localPlayerIds, this.gameMode, this.id);

            // We only want to handle events generated by the model when we are not
            // receiving instructions from the outside (ie. only if we are in local mode,
            // or in server mode)
            if (Constants.getMode() === Constants.MODE_SERVER || Constants.getMode() === Constants.MODE_CLIENT_LOCAL) {
                this.roundController.addEventListener(this._roundModelEventHandler, this, this.id);
            }
            // Attach other event listeners.
            for (const roundEventListener of this.roundEventListeners) {
                this.roundController.addEventListener(roundEventListener.callback, roundEventListener.context, this.id);
            }
        } else {
            this.log.error(`Attempt to create round in game which is currently in state ${this.model.getState()}`);
        }
    }

